-- DÀNH RIÊNG CHO POSTGRESQL (PostgreSQL 14 / 15 / 16 / 17 / 18)
-- ĐÃ TỐI ƯU HÓA: 14 BẢNG CHUẨN 3NF (Loại bỏ bảng tạm & Tinh gọn giải đấu)
