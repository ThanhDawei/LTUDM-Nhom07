-- QUIZZLIVE DATABASE SCHEMA - NHÓM 07: TRANH TÀI KIẾN THỨC
-- DÀNH RIÊNG CHO POSTGRESQL (PostgreSQL 14 / 15 / 16 / 17 / 18)
